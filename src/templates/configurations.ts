/**
 * Templates that translate high-level POV blueprint primitives (SLA policies,
 * email channels, PLuG widget config, integrations) into structured
 * `ui_guidance_sections`. These features are not API-automatable — but they
 * are demanded in nearly every POV. The agent's contribution is to produce a
 * tight, accurate playbook the SE can follow without inventing menu paths.
 */

import { DEMO_DOC_HREF, DEVELOPER_PORTAL_HREF } from "./index.js";

export type UiGuidanceSection = {
  title: string;
  doc_links?: string[];
  steps: string[];
};

