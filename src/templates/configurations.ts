// ---------------- SLA policies ----------------

export type SlaSeverityTargets = {
  /** Target time-to-first-response strings, keyed by priority (p0..p3). */
  first_response?: Partial<Record<"p0" | "p1" | "p2" | "p3", string>>;
  /** Target time-to-resolution strings, keyed by priority. */
  resolution?: Partial<Record<"p0" | "p1" | "p2" | "p3", string>>;
};

export type SlaPolicyInput = {
  name: string;
  /** Optional human description (e.g. "Apply to accounts tagged Enterprise"). */
  description?: string;
  /** Apply to all accounts unless `applies_to` narrows it. */
  applies_to?: string;
  targets: SlaSeverityTargets;
  /** Optional escalation note (e.g. "Auto-escalate at 80% of target"). */
  escalation?: string;
};

const PRIORITY_LABEL: Record<string, string> = {
  p0: "p0 (blocker)",
  p1: "p1 (high)",
  p2: "p2 (medium)",
  p3: "p3 (low)",
};

function formatTargets(label: string, map?: Partial<Record<string, string>>): string | null {
  if (!map) return null;
  const parts = (["p0", "p1", "p2", "p3"] as const)
    .filter((k) => map[k])
    .map((k) => `${PRIORITY_LABEL[k]} ≤ ${map[k]}`);
  if (!parts.length) return null;
  return `${label}: ${parts.join(", ")}`;
}

export function slaGuidance(policies: SlaPolicyInput[]): UiGuidanceSection {
  const steps: string[] = [
    "Settings → SLA Policies → Create",
    "Recreate each policy below, matching the priority targets exactly.",
  ];
  for (const p of policies) {
    steps.push("");
    steps.push(`Policy: ${p.name}${p.applies_to ? ` (applies to ${p.applies_to})` : ""}`);
    if (p.description) steps.push(`  Notes: ${p.description}`);
    const fr = formatTargets("First-response", p.targets.first_response);
    const rs = formatTargets("Resolution", p.targets.resolution);
    if (fr) steps.push(`  ${fr}`);
    if (rs) steps.push(`  ${rs}`);
    if (p.escalation) steps.push(`  Escalation: ${p.escalation}`);
  }
  return {
    title: "Configure SLA policies",
    doc_links: ["https://devrev.ai/docs/product/sla", DEMO_DOC_HREF],
    steps,
  };
}

// ---------------- Email channels ----------------

export type EmailChannelInput = {
  /** Customer-facing inbound address (e.g. "support@acme.com"). */
  address: string;
  /** Optional auto-classification keywords → part name hints. */
  keyword_routing?: { keyword: string; route_to: string }[];
  /** Whether to enable auto-acknowledgement. */
  auto_acknowledge?: boolean;
};

export function emailChannelsGuidance(channels: EmailChannelInput[]): UiGuidanceSection {
  const steps: string[] = [
    "Settings → Channels → Email",
    "DevRev will assign you a forwarding address for each inbox.",
  ];
  for (const c of channels) {
    steps.push("");
    steps.push(`Inbound address: ${c.address}`);
    steps.push(
      "  Configure forwarding from your email provider to the DevRev-supplied address.",
    );
    if (c.auto_acknowledge !== false) {
      steps.push("  Enable auto-acknowledgement template for new ticket creation.");
    }
    if (c.keyword_routing?.length) {
      steps.push("  Subject/keyword routing:");
      for (const r of c.keyword_routing) {
        steps.push(`    - "${r.keyword}" → ${r.route_to}`);
      }
    }
  }
  steps.push("");
  steps.push("Outbound email — defaults that surprise customers:");
  steps.push(
    "  By default the 'From' address is the workspace, not the support agent. Replies look like they come from a generic queue.",
  );
  steps.push(
    "  In the email channel settings, enable 'use the name of the logged-in user as sender' so outbound mail shows the agent's display name and address.",
  );
  steps.push(
    "  By default 'created_by' on email-originated tickets is 'Email Integration Bot'. If the customer wants the agent to appear as the creator, configure the channel to attribute creation to the responding agent at first reply.",
  );
  return {
    title: "Configure email support channels",
    doc_links: ["https://devrev.ai/docs/product/email"],
    steps,
  };
}

// ---------------- PLuG widget ----------------

export type PlugConfigInput = {
  /** Welcome message users see when they open the widget. */
  welcome_message?: string;
  /** Hex/named color used for the widget primary brand. */
  primary_color?: string;
  /** Whether AI agent answers L1 questions before falling back to a ticket. */
  ai_agent_enabled?: boolean;
  /** Whether to fall back to creating a ticket if the AI can't resolve. */
  fallback_to_ticket?: boolean;
  /** Optional notes about KB grounding (e.g. which KB sections to use). */
  ai_grounding_notes?: string;
};

export function plugGuidance(cfg: PlugConfigInput): UiGuidanceSection {
  const steps: string[] = [
    "Settings → PLuG → Widget",
    "Copy the JavaScript snippet and add it to your site's <head> (or deploy via GTM).",
  ];
  if (cfg.welcome_message) {
    steps.push(`Set welcome message: ${JSON.stringify(cfg.welcome_message)}`);
  }
  if (cfg.primary_color) {
    steps.push(`Set primary brand color: ${cfg.primary_color}`);
  }
  if (cfg.ai_agent_enabled !== false) {
    steps.push("Enable the AI agent for L1 deflection.");
    steps.push(
      "  Ground the AI on the KB articles seeded by this blueprint (Settings → AI Agent → Sources).",
    );
    if (cfg.ai_grounding_notes) {
      steps.push(`  Notes: ${cfg.ai_grounding_notes}`);
    }
  }
  if (cfg.fallback_to_ticket !== false) {
    steps.push("Enable fallback to ticket creation when the AI cannot resolve.");
  }
  steps.push("");
  steps.push(
    "Customer-portal auth limitation: the customer-facing portal does NOT support federated login (SAML / OIDC). End users authenticate via email + magic-link only. Surface this early in the POV if the customer is expecting SSO for their end users.",
  );
  return {
    title: "Deploy the PLuG chat widget",
    doc_links: ["https://devrev.ai/docs/product/plug"],
    steps,
  };
}

