export function integrationsGuidance(items: IntegrationInput[]): UiGuidanceSection[] {
  return items.map((it) => {
    const key = (typeof it === "string" ? it : it.name) as IntegrationKey;
    const base = INTEGRATION_GUIDES[key];
    if (!base) {
      return {
        title: `Configure ${key}`,
        steps: [
          `No template for "${key}". Document the setup steps in your runbook before the demo.`,
          `See ${DEVELOPER_PORTAL_HREF} for snap-in / integration developer docs.`,
        ],
      };
    }
    if (typeof it === "string" || !it.notes) return base;
    return { ...base, steps: [...base.steps, "", `Customer notes: ${it.notes}`] };
  });
}

